import test from "node:test";
import assert from "node:assert/strict";
import { selectForegroundValidationCommand as select } from "../extensions/code/repositories/foregroundValidation";
import { detectRepositoryProfileV2, parseRepositoryProfileV2 } from "../extensions/code/repositories/RepositoryProfileV2";

function fixture() {
  const profile = detectRepositoryProfileV2({ key: "select", displayName: "Select", repositoryRoot: "/repo", defaultBranch: "main",
    files: ["package.json", "package-lock.json", ".node-version"], fileContents: { ".node-version": "22.11.0" } });
  const common = { projectId: "root", executable: "npm", cwd: ".", timeoutMs: 300000, network: "disabled" as const, credentialPolicy: "none" as const, lockfile: null };
  // Actual catalog shape generated by the previous pinned version.
  return parseRepositoryProfileV2({ ...profile, validationCatalog: [
    { ...common, id: "root-npm-test", phase: "fast", args: ["run", "test"] },
    { ...common, id: "root-npm-build", phase: "full", args: ["run", "build"] },
  ] });
}

test("already trusted Node profiles select test and build rather than two build receipts", () => {
  const profile = fixture();
  assert.deepEqual(select(profile, "root", "validation_targeted").args, ["run", "test"]);
  assert.deepEqual(select(profile, "root", "validation_full").args, ["run", "build"]);
});

test("two-command legacy profiles retain coverage and larger catalogs refuse omitted checks", () => {
  const profile = fixture();
  profile.validationCatalog = profile.validationCatalog.map((row, index) => ({ ...row, phase: "full", id: `root-full-${index + 1}` }));
  assert.deepEqual(select(profile, "root", "validation_targeted").args, ["run", "test"]);
  assert.deepEqual(select(profile, "root", "validation_full").args, ["run", "build"]);
  profile.validationCatalog.push({ ...profile.validationCatalog[0], id: "root-full-3", args: ["run", "lint"] });
  assert.deepEqual(select(profile, "root", "validation_fast").args, ["run", "test"], "partial diagnostic checks remain available");
  assert.deepEqual(select(profile, "root", "validation_targeted").args, ["run", "test"]);
  assert.throws(() => select(profile, "root", "validation_full"), { code: "sandbox_validation_scope_incomplete" });
});

test("ambiguous fast or targeted scope cannot silently select an unrelated green full command", () => {
  const profile = fixture();
  profile.validationCatalog.push({ ...profile.validationCatalog[0], id: "root-other-test" });
  assert.throws(() => select(profile, "root", "validation_targeted"), { code: "sandbox_validation_command_ambiguous" });
  profile.validationCatalog = profile.validationCatalog.map(row => ({ ...row, phase: "targeted" }));
  assert.throws(() => select(profile, "root", "validation_targeted"), { code: "sandbox_validation_command_ambiguous" });
  assert.throws(() => select(profile, "another-project", "validation_targeted"), { code: "sandbox_validation_command_unavailable" });
});

test("explicit targeted commands and a sole stronger full command remain usable", () => {
  const profile = fixture();
  profile.validationCatalog[0].phase = "targeted";
  assert.equal(select(profile, "root", "validation_targeted").id, "root-npm-test");
  profile.validationCatalog.shift();
  assert.throws(() => select(profile, "root", "validation_targeted"), { code: "sandbox_validation_scope_incomplete" });
  profile.validationCatalog[0].args = ["run", "verify"];
  assert.equal(select(profile, "root", "validation_targeted").id, "root-npm-build", "an explicitly trusted complete command remains available");
  assert.throws(() => select(profile, "root", "lockfile_restore"), { code: "sandbox_validation_command_unavailable" });
});

test("non-Node profiles retain the stronger full fallback instead of a fast compile check", () => {
  const profile = detectRepositoryProfileV2({ key: "python", displayName: "Python", repositoryRoot: "/repo", defaultBranch: "main",
    files: ["pyproject.toml", ".python-version"], fileContents: { ".python-version": "3.12.3" } });
  const common = { projectId: "root", executable: "python", cwd: ".", timeoutMs: 300000, network: "disabled" as const, credentialPolicy: "none" as const, lockfile: null };
  profile.validationCatalog = [
    { ...common, id: "root-compile", phase: "fast", args: ["-m", "compileall", "."] },
    { ...common, id: "root-pytest", phase: "full", args: ["-m", "pytest"] },
  ];
  assert.equal(select(parseRepositoryProfileV2(profile), "root", "validation_targeted").id, "root-pytest");
});
